// Catalan for ca, Spanish for es and the other languages of Spain, English for every other visitor.
export function detect(): Lang {
  for (const l of navigator.languages?.length ? navigator.languages : [navigator.language]) {
    const p = l.slice(0, 2).toLowerCase();
    if (p === "ca") return "ca";
    if (p === "es" || p === "gl" || p === "eu") return "es";
    if (p === "en") return "en";
  }
  return "en";
}

